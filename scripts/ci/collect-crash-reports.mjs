// scripts/ci/collect-crash-reports.mjs
// Gather one cross-version job's crash evidence into the folder the composite uploads. An
// artifact on a public repo can be downloaded by any GitHub account and the editor process
// holds the WS auth token, so only text goes in: the editor logs, the Godot `.ips` reports on
// macOS, and the stack text a debugger prints here on the runner, `cdb` over a Windows minidump
// and `gdb -batch -ex bt` over an editor's Linux core. A dump or a core holds the process's
// memory and is never copied. docs/dev/crash-reports.md explains how to read what this gathers.
//
// The OS reporter writes on its own schedule, so when an editor is expected to have died
// (a failed leg, or an editor gone at teardown) the macOS and Windows reports get a bounded
// wait. macOS's reporter writes after the process is gone, so a green macOS leg holds too, for a
// crash at exit. A green Linux or Windows leg waits for nothing.
//
// It writes `upload=true|false` to $GITHUB_OUTPUT. The leg uploads when there is a report,
// a log of a failed boot attempt, a failed or cancelled leg, or an editor gone at teardown;
// otherwise the leg's job log already says everything.
//
// Usage: node scripts/ci/collect-crash-reports.mjs --os <linux|macos|windows> --out <dir>
//          --reports <dir> [--editor-bin <path>] [--leg-status <status>]
//          [--editor-gone <reason>] [--log <file>]...
// Exit codes: 0 gathered, a report or not · 1 an unexpected error (the composite's step
// continues on error, so it cannot fail the leg) · 2 bad arguments.
import { spawnSync } from "node:child_process";
import {
  appendFileSync,
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  realpathSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { basename, join } from "node:path";
import { setTimeout as pause } from "node:timers/promises";
import { fileURLToPath } from "node:url";

export const REPORT_NAME = {
  macos: /^godot.*\.ips$/i,
  // LocalDumps is machine-wide and names a dump after its executable; a dump of any other
  // process is not the editor's crash, so it is not read.
  windows: /^godot.*\.dmp$/i,
};
const CORE_NAME = /^core\./;
// kernel.core_pattern is machine-wide too, and a core's file name carries the crashing thread's
// name rather than the executable's. So gdb's line decides: the first token of the command line
// is the executable, and the tokens after it can hold any text. A core of any other process is
// not the editor's crash, so its stack is not uploaded.
const CORE_COMMAND = /^Core was generated by `(\S*?)(?:'\.)?(?:\s|$)/m;
const EDITOR_EXECUTABLE = /^godot/i;
const FAILED_BOOT_LOG = /^editor-attempt-/;

// A minimal dump is stacks and modules. One far past this is not minimal, whatever the
// registry was asked for, so it is neither copied nor read, and the step's fuse is not spent on it.
const MAX_REPORT_BYTES = 64 * 1024 * 1024;

const POLL_MS = 2_000;
// The reports of a boot's three attempts arrive one by one: stop once none has come for this long.
const SETTLE_MS = 15_000;
// Every death comes before this step, so a report still on its way lands within the reporter's
// latency of the wait's start, however early another one came. The slowest seen on a hosted macOS
// runner took 18.5 s, past SETTLE_MS, so an earlier report going quiet cannot end the wait before this.
const REPORTER_LATENCY_MS = 24_000;
const MAX_WAIT_MS = 60_000;

// One debugger run. A run past it keeps the text it printed; the dumps read before it keep theirs.
const DEBUGGER_TIMEOUT_MS = 120_000;
const DEBUGGER_MAX_OUTPUT_BYTES = 16 * 1024 * 1024;
const APT_TIMEOUT_MS = 240_000;

// The crash analysis and every thread's stack. Neither asks for the environment block the dump holds.
const CDB_COMMANDS = "!analyze -v; ~* k; q";

/**
 * Whether the leg's state says an editor may have died, which is worth waiting for a report.
 *
 * @param legStatus - the composite's result so far: `success`, `failure` or `cancelled`.
 * @param editorGone - why the teardown found no editor to stop; empty when it found one.
 */
export function expectsEditorDeath(legStatus, editorGone) {
  return legStatus === "failure" || legStatus === "cancelled" || Boolean(editorGone);
}

/**
 * Gathers the logs and the OS's reports into `outDir`, with a `collected.txt` saying what
 * it found, so an artifact without a report explains itself.
 *
 * @param options.os - `linux`, `macos` or `windows`.
 * @param options.outDir - the folder the composite uploads.
 * @param options.reportsDir - where this OS's reporter writes.
 * @param options.logs - logs to copy; one the job never wrote is noted and skipped.
 * @param options.expectDeath - wait for a macOS or Windows report to arrive.
 * @param options.holdForExitCrash - with no death expected, still wait the reporter's latency; a
 *   report found by then is waited for as one from an expected death is.
 * @param options.backtrace - returns a Linux core's or a Windows dump's stacks as text.
 * @param options.sleep - waits the given ms, or a test's stand-in.
 * @returns how many reports were gathered, whether to upload, and the notes.
 */
export async function collectCrashReports({
  os,
  outDir,
  reportsDir,
  logs,
  expectDeath,
  holdForExitCrash = false,
  backtrace,
  sleep = pause,
}) {
  mkdirSync(outDir, { recursive: true });
  const notes = [];
  for (const log of logs) {
    if (!existsSync(log)) {
      notes.push(`${log}: not written by this job`);
      continue;
    }
    copyFileSync(log, join(outDir, basename(log)));
  }
  let reports;
  if (os === "linux") {
    reports = writeBacktraces(reportsDir, outDir, backtrace, notes);
  } else {
    const names = await awaitReports(REPORT_NAME[os], reportsDir, expectDeath, holdForExitCrash, sleep, notes);
    reports =
      os === "windows"
        ? writeDumpStacks(names, reportsDir, outDir, backtrace, notes)
        : copyReports(names, reportsDir, outDir);
  }
  const failedBoots = readdirSync(outDir).filter((name) => FAILED_BOOT_LOG.test(name)).length;
  notes.push(`reports gathered: ${reports}; failed boot attempts logged: ${failedBoots}`);
  writeFileSync(join(outDir, "collected.txt"), `${notes.join("\n")}\n`);
  return { reports, upload: reports > 0 || failedBoots > 0 || expectDeath, notes };
}

function listDir(dir) {
  return existsSync(dir) ? readdirSync(dir) : [];
}

function writeBacktraces(coreDir, outDir, backtrace, notes) {
  const cores = listDir(coreDir).filter((name) => CORE_NAME.test(name));
  let reports = 0;
  for (const name of cores) {
    const text = backtrace(join(coreDir, name));
    const command = CORE_COMMAND.exec(text)?.[1];
    // Text that names no executable, as when gdb is missing or gave up, is kept and counted: it
    // may be the editor's, and a false report costs less than a lost crash.
    if (command && !EDITOR_EXECUTABLE.test(basename(command))) {
      notes.push(`a core of ${basename(command)}: not the editor, so its stack is not uploaded`);
      continue;
    }
    writeFileSync(join(outDir, `${name}.backtrace.txt`), text);
    reports += 1;
  }
  notes.push(`${coreDir}: ${cores.length} core file(s), read on the runner and not uploaded`);
  return reports;
}

// Each text is written as its dump is read, so a fuse kill keeps the ones already done.
function writeDumpStacks(names, reportsDir, outDir, backtrace, notes) {
  for (const name of names) {
    writeFileSync(join(outDir, `${name.replace(/\.dmp$/i, "")}.cdb.txt`), backtrace(join(reportsDir, name)));
  }
  notes.push(`${reportsDir}: ${names.length} dump(s) passed to cdb on the runner and not uploaded`);
  return names.length;
}

function copyReports(names, reportsDir, outDir) {
  for (const name of names) copyFileSync(join(reportsDir, name), join(outDir, name));
  return names.length;
}

async function awaitReports(pattern, reportsDir, expectDeath, holdForExitCrash, sleep, notes) {
  const list = () => listDir(reportsDir).filter((name) => pattern.test(name));
  let names = list();
  let waitedMs = 0;
  let quietMs = 0;
  // With no report yet, only an expected death is worth waiting on past the reporter's latency.
  const settled = () => waitedMs >= REPORTER_LATENCY_MS && (names.length > 0 ? quietMs >= SETTLE_MS : !expectDeath);
  while ((expectDeath || holdForExitCrash) && waitedMs < MAX_WAIT_MS && !settled()) {
    await sleep(POLL_MS);
    waitedMs += POLL_MS;
    const current = list();
    quietMs = current.length === names.length ? quietMs + POLL_MS : 0;
    names = current;
  }
  notes.push(
    `${reportsDir}: ${names.length} report(s) after waiting ${waitedMs} ms; all files there: ${listDir(reportsDir).length}`,
  );
  return names.filter((name) => {
    const bytes = statSync(join(reportsDir, name)).size;
    if (bytes <= MAX_REPORT_BYTES) return true;
    notes.push(`${name}: left on the runner, ${bytes} bytes is not a minimal report`);
    return false;
  });
}

// The apt fetch is spent only on a leg that has a core to read.
function ensureGdb() {
  if (!spawnSync("gdb", ["--version"], { stdio: "ignore" }).error) return "gdb was already installed";
  const apt = ["-o", "DPkg::Lock::Timeout=60", "-y"];
  for (const step of [["update"], ["install", "--no-install-recommends", "gdb"]]) {
    const run = spawnSync("sudo", ["apt-get", ...apt, ...step], { stdio: "ignore", timeout: APT_TIMEOUT_MS });
    if (run.status !== 0) return `apt-get ${step[0]} failed (status ${run.status}, ${run.error ?? "no error"})`;
  }
  return "gdb installed through apt";
}

function gdbBacktrace(editorBin, core) {
  const args = ["-batch", "-ex", "bt", ...(editorBin ? [editorBin] : []), "-c", core];
  const run = spawnSync("gdb", args, {
    encoding: "utf8",
    timeout: DEBUGGER_TIMEOUT_MS,
    maxBuffer: DEBUGGER_MAX_OUTPUT_BYTES,
  });
  if (run.error) return `gdb did not finish: ${run.error}\n${run.stdout ?? ""}`;
  return `${run.stdout}${run.stderr}`;
}

// Where the hosted Windows runner has the SDK's Debugging Tools.
function cdbPath() {
  const programFiles = process.env["ProgramFiles(x86)"] ?? "C:\\Program Files (x86)";
  return join(programFiles, "Windows Kits", "10", "Debuggers", "x64", "cdb.exe");
}

function cdbStacks(dump) {
  const cdb = cdbPath();
  if (!existsSync(cdb)) {
    const note = `cdb is not at ${cdb}: ${basename(dump)} was not read and stays on the runner`;
    console.log(note);
    return `${note}\n`;
  }
  const run = spawnSync(cdb, ["-z", dump, "-lines", "-c", CDB_COMMANDS], {
    encoding: "utf8",
    // All its commands come from -c; an open stdin could only hold it until the timeout.
    stdio: ["ignore", "pipe", "pipe"],
    timeout: DEBUGGER_TIMEOUT_MS,
    maxBuffer: DEBUGGER_MAX_OUTPUT_BYTES,
  });
  if (run.error) return `cdb did not finish: ${run.error}\n${run.stdout ?? ""}`;
  return `${run.stdout}${run.stderr}`;
}

function parseArgs(argv) {
  const args = { logs: [], editorBin: "", legStatus: "", editorGone: "" };
  const flags = {
    "--os": "os",
    "--out": "outDir",
    "--reports": "reportsDir",
    "--editor-bin": "editorBin",
    "--leg-status": "legStatus",
    "--editor-gone": "editorGone",
  };
  for (let i = 0; i < argv.length; i += 2) {
    const [flag, value] = [argv[i], argv[i + 1]];
    if (value === undefined) return undefined;
    if (flag === "--log") args.logs.push(value);
    else if (flag in flags) args[flags[flag]] = value;
    else return undefined;
  }
  const known = args.os === "linux" || args.os === "macos" || args.os === "windows";
  return known && args.outDir && args.reportsDir ? args : undefined;
}

async function main(argv) {
  const args = parseArgs(argv);
  if (!args) {
    console.error(
      "usage: node scripts/ci/collect-crash-reports.mjs --os <linux|macos|windows> --out <dir> --reports <dir> " +
        "[--editor-bin <path>] [--leg-status <status>] [--editor-gone <reason>] [--log <file>]...",
    );
    return 2;
  }
  let gdbNote;
  const backtrace = (core) => {
    gdbNote ??= ensureGdb();
    return `${gdbNote}\n${gdbBacktrace(args.editorBin, core)}`;
  };
  const { reports, upload, notes } = await collectCrashReports({
    os: args.os,
    outDir: args.outDir,
    reportsDir: args.reportsDir,
    logs: args.logs,
    expectDeath: expectsEditorDeath(args.legStatus, args.editorGone),
    holdForExitCrash: args.os === "macos",
    backtrace: args.os === "windows" ? cdbStacks : backtrace,
  });
  for (const note of notes) console.log(note);
  if (reports > 0) {
    console.log(`::warning title=Crash report::${reports} crash report(s) gathered; see docs/dev/crash-reports.md`);
  }
  if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `upload=${upload}\n`);
  return 0;
}

// Real paths on both sides, so a symlinked checkout still runs the script.
if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  process.exitCode = await main(process.argv.slice(2));
}
